#!/usr/bin/env python3
"""Builds the Brittany's images into components/wb_ui/dog/ for both screen designs.

Draws from tools/dog/dog_art.py (SVG) and converts like tools/make_pippa_assets.py does
for Pippa (RGB565A8, LZ4 compressed, via components/lvgl/scripts/LVGLImage.py), so
the 2.0 screens can show her exactly where they show Pippa:

  img_dog_<look>.c        six outfits + base, 260x252 stage, cropped to the alpha
                          bounding box with the crop offset recorded
  img_dog_mini_<look>.c   forecast-card minis, drawn at MINI_H px tall (not scaled at
                          runtime: this LVGL build can't scale compressed images)
  img_dog_head.c          head badge for the 2.0 boot / setup / error screens
  img_dog_head_thumb.c    Settings pill thumbnail
  img_dog_head_classic.c  head for the classic boot and setup screens (110 px, like
                          the classic cats)
  dog_sets.h / dog_sets.c descriptors and stage positions
  dog_assets.cmake        WB_DOG_HEAD_SRCS (both designs), WB_DOG_STAGE_SRCS (2.0)

Run from anywhere:  python3 tools/dog/make_dog_assets.py
Needs: pip install resvg-py pillow pypng
"""
import io
import os
import subprocess
import sys

import resvg_py
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import dog_art  # noqa: E402

OUT = os.path.join(ROOT, "components", "wb_ui", "dog")
PNG = os.path.join(HERE, "build")
LVGLIMAGE = os.path.join(ROOT, "components", "lvgl", "scripts", "LVGLImage.py")
MINI_H = 104       # same as Pippa's forecast minis
HEAD_H = 116       # Pippa's head badge image is 130x108; the badge disc is 160
THUMB_H = 32       # Pippa's pill thumbnails are 40x32
CLASSIC_HEAD = 110 # the classic cats are 110 px

LOOKS = dog_art.OUTFITS + ["base"]   # look order matches outfit.h: dress, pants, snow, rain, hot, fall


def render(svg, w, h):
    data = bytes(resvg_py.svg_to_bytes(svg_string=svg, width=w, height=h))
    return Image.open(io.BytesIO(data)).convert("RGBA")


def to_c(im, name):
    """Crop to the alpha bbox, convert, return the bbox (x, y, w, h)."""
    bb = im.getchannel("A").getbbox()
    path = os.path.join(PNG, name + ".png")
    im.crop(bb).save(path)
    subprocess.run([sys.executable, LVGLIMAGE, "--ofmt", "C", "--cf", "RGB565A8", "--compress", "LZ4",
                    "-o", OUT, "--name", name, path], check=True, stdout=subprocess.DEVNULL)
    for produced in (os.path.join(OUT, name + ".png.c"), os.path.join(OUT, name + ".c")):
        if os.path.exists(produced) and produced != os.path.join(OUT, name + ".c"):
            os.replace(produced, os.path.join(OUT, name + ".c"))
    return bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PNG, exist_ok=True)
    head_srcs, stage_srcs, pos, minis = [], [], {}, []

    for look in LOOKS:
        name = f"img_dog_{look}"
        x, y, _, _ = to_c(render(dog_art.stage_svg(look), dog_art.W, dog_art.H), name)
        pos[look] = (x, y)
        stage_srcs.append(name)
        if look != "base":
            mw = round(dog_art.W * MINI_H / dog_art.H)
            to_c(render(dog_art.stage_svg(look), mw, MINI_H), f"img_dog_mini_{look}")
            minis.append(look)
            stage_srcs.append(f"img_dog_mini_{look}")

    hw, hh = 150, 134   # head_svg's own size
    for name, h in (("img_dog_head", HEAD_H), ("img_dog_head_thumb", THUMB_H),
                    ("img_dog_head_classic", CLASSIC_HEAD)):
        to_c(render(dog_art.head_svg(), round(hw * h / hh), h), name)
        head_srcs.append(name)

    with open(os.path.join(OUT, "dog_sets.h"), "w") as f:
        f.write("/* The Brittany: generated by tools/dog/make_dog_assets.py from tools/dog/dog_art.py.\n"
                " * Do not edit by hand; rerun that script instead. */\n#pragma once\n#include \"lvgl.h\"\n\n")
        for n in head_srcs + stage_srcs:
            f.write(f"LV_IMAGE_DECLARE({n});\n")
        f.write("\n/* Index = outfit look (outfit.h order: dress, pants, snow, rain, hot, fall), then the\n"
                " * undressed base. Positions are in the 260x252 stage, like Pippa's. */\n"
                f"#define WB_DOG_LOOKS {len(dog_art.OUTFITS)}\n#define WB_DOG_BASE {len(dog_art.OUTFITS)}\n"
                f"extern const lv_image_dsc_t *const WB_DOG_SPRITES[{len(LOOKS)}];\n"
                f"extern const lv_point_t WB_DOG_SPRITE_POS[{len(LOOKS)}];\n"
                f"extern const lv_image_dsc_t *const WB_DOG_MINIS[{len(dog_art.OUTFITS)}];\n")
    with open(os.path.join(OUT, "dog_sets.c"), "w") as f:
        f.write("/* Generated by tools/dog/make_dog_assets.py. Do not edit. */\n#include \"dog_sets.h\"\n\n")
        f.write(f"const lv_image_dsc_t *const WB_DOG_SPRITES[{len(LOOKS)}] = {{"
                + ", ".join(f"&img_dog_{l}" for l in LOOKS) + "};\n")
        f.write(f"const lv_point_t WB_DOG_SPRITE_POS[{len(LOOKS)}] = {{"
                + ", ".join(f"{{{pos[l][0]}, {pos[l][1]}}}" for l in LOOKS) + "};\n")
        f.write(f"const lv_image_dsc_t *const WB_DOG_MINIS[{len(dog_art.OUTFITS)}] = {{"
                + ", ".join(f"&img_dog_mini_{l}" for l in minis) + "};\n")
    with open(os.path.join(OUT, "dog_assets.cmake"), "w") as f:
        f.write("# Generated by tools/dog/make_dog_assets.py.\n")
        f.write("set(WB_DOG_HEAD_SRCS\n" + "".join(f"    dog/{n}.c\n" for n in head_srcs) + ")\n")
        f.write("set(WB_DOG_STAGE_SRCS\n    dog/dog_sets.c\n" + "".join(f"    dog/{n}.c\n" for n in stage_srcs) + ")\n")
    print(f"{len(stage_srcs)} stage images, {len(head_srcs)} heads -> {OUT}")


if __name__ == "__main__":
    main()
