#!/usr/bin/env python3
"""Builds the Routine page's step pictures into components/wb_ui/routine/ (2.0 screens).

Draws from tools/routine/routine_icons.py (SVG) and converts like tools/dog/make_dog_assets.py
(RGB565A8, RLE compressed, via components/lvgl/scripts/LVGLImage.py):

  img_rt_<name>.c     one per picture, ICON px square (the bar's finish line: SIZES)
  routine_icons.h     declarations
  routine_icons.cmake WB_ROUTINE_SRCS

Run from anywhere:  python3 tools/routine/make_routine_icons.py
Needs: pip install resvg-py pillow pypng lz4
"""
import io
import os
import subprocess
import sys

import resvg_py
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import routine_icons  # noqa: E402

OUT = os.path.join(ROOT, "components", "wb_ui", "routine")
PNG = os.path.join(HERE, "build")
LVGLIMAGE = os.path.join(ROOT, "components", "lvgl", "scripts", "LVGLImage.py")
ICON = 72


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PNG, exist_ok=True)
    names = []
    for key, svg in routine_icons.ICONS.items():
        name = f"img_rt_{key}"
        size = routine_icons.SIZES.get(key, ICON)
        data = bytes(resvg_py.svg_to_bytes(svg_string=svg, width=size, height=size))
        path = os.path.join(PNG, name + ".png")
        Image.open(io.BytesIO(data)).convert("RGBA").save(path)
        subprocess.run([sys.executable, LVGLIMAGE, "--ofmt", "C", "--cf", "RGB565A8", "--compress", "RLE",
                        "-o", OUT, "--name", name, path], check=True, stdout=subprocess.DEVNULL)
        produced = os.path.join(OUT, name + ".png.c")
        if os.path.exists(produced):
            os.replace(produced, os.path.join(OUT, name + ".c"))
        names.append(name)
    with open(os.path.join(OUT, "routine_icons.h"), "w") as f:
        f.write("/* Generated by tools/routine/make_routine_icons.py. Do not edit. */\n#pragma once\n"
                "#include \"lvgl.h\"\n\n" + "".join(f"LV_IMAGE_DECLARE({n});\n" for n in names))
    with open(os.path.join(OUT, "routine_icons.cmake"), "w") as f:
        f.write("# Generated by tools/routine/make_routine_icons.py.\nset(WB_ROUTINE_SRCS\n"
                + "".join(f"    routine/{n}.c\n" for n in names) + ")\n")
    print(f"{len(names)} routine pictures -> {OUT}")


if __name__ == "__main__":
    main()
